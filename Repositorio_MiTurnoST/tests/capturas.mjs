import { chromium } from 'playwright';
import { resolve } from 'node:path';
const url = 'file://' + resolve('prototipo/index.html');
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH });
const p = await b.newPage({ viewport: { width: 1280, height: 820 }, deviceScaleFactor: 1.5 });
await p.goto(url);
const ev = (f, a) => p.evaluate(f, a);
const shot = async (n, full=false, keep=false) => { await p.waitForTimeout(250); if(!keep) await p.evaluate(()=>document.querySelectorAll('.toast').forEach(t=>t.remove())); await p.screenshot({ path: `docs/img/${n}.png`, fullPage: full }); };
await ev(() => { localStorage.clear(); localStorage.setItem('miturnost.tema','light'); }); await p.reload();
await shot('01_login');
await p.click('button:has-text("Estudiante")'); await shot('02_disponibilidad');
await p.click('.blk.st-libre:not([disabled]) >> nth=0'); await shot('03_confirmar_reserva');
await p.click('button:has-text("Confirmar reserva")'); await shot('04_reserva_confirmada', false, true);
await p.click('button:has-text("Ver mis reservas")'); await shot('05_mis_reservas');
await p.click('button:has-text("Salir")'); await p.click('button:has-text("Personal de mesón")'); await shot('06_meson');
await p.click('button:has-text("Validar y entregar"):not([disabled]) >> nth=0').catch(()=>{});
await shot('07_validar_entrega');
await p.keyboard.press('Escape');
await p.click('button:has-text("Salir")'); await p.click('button:has-text("Administración")'); await shot('08_administracion', true);
await ev(() => { document.documentElement.dataset.theme='dark'; location.hash='disponibilidad'; window.MiTurno.render(); }); await shot('09_modo_oscuro');
await ev(() => { document.documentElement.dataset.theme='light'; window.MiTurno.render(); });
await p.setViewportSize({ width: 390, height: 844 }); await ev(() => { window.MiTurno.Acciones.login('camila.rojas@alumnos.santotomas.cl'); location.hash='disponibilidad'; window.MiTurno.render(); }); await shot('10_movil');
await b.close();
